-- Canonical account-level billing for Mail. Legacy per-app subscriptions are
-- retained so paid history is never destroyed during the migration.
CREATE TYPE "MailBillingAccountStatus" AS ENUM ('ACTIVE', 'SUSPENDED', 'CLOSED');

CREATE TABLE "mail_billing_accounts" (
    "id" TEXT NOT NULL,
    "ownerUserId" TEXT NOT NULL,
    "status" "MailBillingAccountStatus" NOT NULL DEFAULT 'ACTIVE',
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,
    CONSTRAINT "mail_billing_accounts_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "mail_billing_accounts_ownerUserId_key"
  ON "mail_billing_accounts"("ownerUserId");
CREATE INDEX "mail_billing_accounts_status_idx"
  ON "mail_billing_accounts"("status");
ALTER TABLE "mail_billing_accounts"
  ADD CONSTRAINT "mail_billing_accounts_ownerUserId_fkey"
  FOREIGN KEY ("ownerUserId") REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE "mail_apps" ADD COLUMN "billingAccountId" TEXT;
CREATE INDEX "mail_apps_billingAccountId_idx" ON "mail_apps"("billingAccountId");
ALTER TABLE "mail_apps"
  ADD CONSTRAINT "mail_apps_billingAccountId_fkey"
  FOREIGN KEY ("billingAccountId") REFERENCES "mail_billing_accounts"("id") ON DELETE SET NULL ON UPDATE CASCADE;

ALTER TABLE "mail_subscriptions" ADD COLUMN "billingAccountId" TEXT;
CREATE UNIQUE INDEX "mail_subscriptions_billingAccountId_key"
  ON "mail_subscriptions"("billingAccountId");
CREATE INDEX "mail_subscriptions_billingAccountId_idx"
  ON "mail_subscriptions"("billingAccountId");
ALTER TABLE "mail_subscriptions"
  ADD CONSTRAINT "mail_subscriptions_billingAccountId_fkey"
  FOREIGN KEY ("billingAccountId") REFERENCES "mail_billing_accounts"("id") ON DELETE SET NULL ON UPDATE CASCADE;

CREATE TABLE "mail_app_seat_allocations" (
    "id" TEXT NOT NULL,
    "billingAccountId" TEXT NOT NULL,
    "mailAppId" TEXT NOT NULL,
    "mailboxSeats" INTEGER NOT NULL DEFAULT 0,
    "domainSlots" INTEGER NOT NULL DEFAULT 1,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,
    CONSTRAINT "mail_app_seat_allocations_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "mail_app_seat_allocations_mailAppId_key"
  ON "mail_app_seat_allocations"("mailAppId");
CREATE UNIQUE INDEX "mail_app_seat_allocations_billingAccountId_mailAppId_key"
  ON "mail_app_seat_allocations"("billingAccountId", "mailAppId");
CREATE INDEX "mail_app_seat_allocations_billingAccountId_idx"
  ON "mail_app_seat_allocations"("billingAccountId");
ALTER TABLE "mail_app_seat_allocations"
  ADD CONSTRAINT "mail_app_seat_allocations_billingAccountId_fkey"
  FOREIGN KEY ("billingAccountId") REFERENCES "mail_billing_accounts"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "mail_app_seat_allocations"
  ADD CONSTRAINT "mail_app_seat_allocations_mailAppId_fkey"
  FOREIGN KEY ("mailAppId") REFERENCES "mail_apps"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- One account per owner is deterministic and safe to rerun in a controlled
-- migration transaction. UUIDs are generated by PostgreSQL from md5 bytes.
INSERT INTO "mail_billing_accounts" ("id", "ownerUserId", "updatedAt")
SELECT md5('mail-billing:' || u."id"), u."id", CURRENT_TIMESTAMP
FROM "users" u
WHERE EXISTS (SELECT 1 FROM "mail_apps" a WHERE a."userId" = u."id")
ON CONFLICT ("ownerUserId") DO NOTHING;

UPDATE "mail_apps" a
SET "billingAccountId" = b."id"
FROM "mail_billing_accounts" b
WHERE b."ownerUserId" = a."userId" AND a."billingAccountId" IS NULL;

-- Link only an unambiguous legacy subscription. Owners with multiple paid
-- app subscriptions stay unlinked until the reconciliation command reviews
-- the periods instead of silently merging or losing entitlements.
UPDATE "mail_subscriptions" s
SET "billingAccountId" = b."id"
FROM "mail_billing_accounts" b
WHERE b."ownerUserId" = s."userId"
  AND s."billingAccountId" IS NULL
  AND (SELECT COUNT(*) FROM "mail_subscriptions" x WHERE x."userId" = s."userId") = 1;

INSERT INTO "mail_app_seat_allocations"
  ("id", "billingAccountId", "mailAppId", "mailboxSeats", "domainSlots", "updatedAt")
SELECT md5('mail-allocation:' || a."id"), a."billingAccountId",
       a."id", COALESCE(s."mailboxCount", 0), 1, CURRENT_TIMESTAMP
FROM "mail_apps" a
LEFT JOIN "mail_subscriptions" s ON s."mailAppId" = a."id"
WHERE a."billingAccountId" IS NOT NULL
ON CONFLICT ("mailAppId") DO NOTHING;
