export function getTemplateFieldLabel(
  field: Pick<TemplateField, 'label' | 'labelAr'>,
  locale: AppLocale,
): string {
  return pickLocaleValue(locale, {
    ar: field.labelAr || field.label,
    en: field.label || field.labelAr,
  });
}

export function getVariantAttributeLabel(
  attribute: Pick<VariantAttribute, 'label' | 'labelAr'>,
  locale: AppLocale,
): string {
  return pickLocaleValue(locale, {
    ar: attribute.labelAr || attribute.label,
    en: attribute.label || attribute.labelAr,
  });
}

export function getTemplateOptionLabel(option: string, locale: AppLocale): string {
  if (locale !== 'en') return option;
  return OPTION_LABEL_EN[option] ?? option;
}
